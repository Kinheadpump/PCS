//! Bitmap pixel font: 5x7 glyphs (plus one descender row) for ASCII 32..=126.
//! We own the data; no font crate. Drawn with rectangles, one per lit pixel.

use macroquad::prelude::{Color, draw_rectangle};

/// Glyph width in font pixels.
pub const GLYPH_W: u32 = 5;
/// Glyph height in font pixels (7 rows plus one descender row).
pub const GLYPH_H: u32 = 8;
/// Horizontal advance per character: glyph width plus one blank column.
pub const ADVANCE: u32 = 6;
/// First character that the font covers.
pub const FIRST: u8 = 32;
/// Last character that the font covers.
pub const LAST: u8 = 126;

