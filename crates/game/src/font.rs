/// The degree sign, the only glyph outside ASCII.
pub const DEGREE_SIGN: char = '\u{b0}';
const DEGREE: [u8; 5] = [0x00, 0x06, 0x09, 0x09, 0x06];

/// The glyph of a character. A character outside 32..=126 shows as `?`, except the degree sign.
pub fn glyph(c: char) -> &'static [u8; 5] {
    if c == DEGREE_SIGN {
        return &DEGREE;
    }
    let code = u32::from(c);
    let index = if (u32::from(FIRST)..=u32::from(LAST)).contains(&code) {
        code - u32::from(FIRST)
    } else {
        u32::from(b'?' - FIRST)
    };
    &GLYPHS[index as usize]
}

/// Width of a text in font pixels (no trailing blank column).
pub fn text_width(text: &str) -> u32 {
    match text.chars().count() as u32 {
        0 => 0,
        n => n * ADVANCE - (ADVANCE - GLYPH_W),
    }
}

/// Draw a text with its top left corner at `(x, y)`. `scale` is screen pixels per font pixel.
pub fn draw_text(text: &str, x: f32, y: f32, scale: u32, color: Color) {
    let s = scale as f32;
    for (i, c) in text.chars().enumerate() {
        let gx = x + (i as u32 * ADVANCE * scale) as f32;
        for (col, bits) in glyph(c).iter().enumerate() {
            for row in 0..GLYPH_H {
                if bits >> row & 1 == 1 {
                    draw_rectangle(gx + col as f32 * s, y + row as f32 * s, s, s, color);
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn font_covers_all_printable_ascii() {
        assert_eq!(GLYPHS.len(), usize::from(LAST - FIRST) + 1);
        for code in FIRST..=LAST {
            let g = glyph(char::from(code));
            if code == b' ' {
                assert!(g.iter().all(|&b| b == 0));
            } else {
                assert!(g.iter().any(|&b| b != 0), "blank glyph for {code}");
            }
        }
    }

    #[test]
    fn glyphs_are_distinct() {
        for (i, a) in GLYPHS.iter().enumerate() {
            for b in &GLYPHS[i + 1..] {
                assert_ne!(a, b);
            }
        }
    }

    #[test]
    fn unknown_characters_show_as_question_mark() {
        assert_eq!(glyph('\u{e9}'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
        assert_ne!(glyph(DEGREE_SIGN), glyph('?'));
    }

    #[test]
    fn text_width_counts_advance_without_trailing_gap() {
        assert_eq!(text_width(""), 0);
        assert_eq!(text_width("A"), 5);
        assert_eq!(text_width("AB"), 11);
    }
}
